// Helper to normalize items to the standardized schema
export function normalizeItem(item, index = 0) {
  const itemId = item.itemId || item.id || `item_${String(index + 1).padStart(3, '0')}`;
  return {
    itemId,
    id: itemId, // backward compatibility
    name: item.name || '',
    category: item.category || 'General',
    floor: item.floor || '1st Floor',
    quantity: item.quantity !== undefined ? item.quantity : (item.qty !== undefined ? item.qty : 1),
    qty: item.quantity !== undefined ? item.quantity : (item.qty !== undefined ? item.qty : 1),
    unit: item.unit || 'pcs',
    sizeSpec: item.sizeSpec || item.size || '',
    size: item.sizeSpec || item.size || '',
    note: item.note !== undefined ? item.note : (item.notes || ''),
    notes: item.note !== undefined ? item.note : (item.notes || ''),
    assignee: item.assignee !== undefined ? item.assignee : (item.assignedTo || ''),
    assignedTo: item.assignee !== undefined ? item.assignee : (item.assignedTo || ''),
    status: item.status || 'pending',
    updatedAt: item.updatedAt || new Date().toISOString()
  };
}

